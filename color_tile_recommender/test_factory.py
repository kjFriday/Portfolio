"""Tests for the Color Voats factory. Run: python -m unittest test_factory"""

import importlib.util
import json
import os
import shutil
import tempfile
import unittest

import algos
import factory

COLORS = algos.palette()
LOGS = [[], [{"color": "#3366cc", "voat": 1}],
        [{"color": "#ffffff", "voat": -1}, {"color": "#ff9900", "voat": 1}, {"color": "#ff9900", "voat": 1},
         {"color": "#003300", "voat": -1}, {"color": "#660000", "voat": -1}, {"color": "#99ccff", "voat": -1}]]


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def reference_rank(preset, voats, colors):
    """What a preset's ranker should return, worked out with algos.py directly."""
    weights = {}
    for name in preset["weights"]:
        weights[name] = preset["weights"][name]["data"]

    def score(name, colors, voats):
        return algos.run_scorer(name, colors, voats, weights[name])

    if preset["algo"] == "blend":
        lists = []
        mix = []
        for name in preset["uses"]:
            lists.append(score(name, colors, voats))
            mix.append(preset["uses"][name])
        return algos.order_by(colors, [algos.blend(lists, mix)])
    if preset["algo"] == "mixer":
        mixer = weights["mixer"]
        return algos.mixer(colors, voats, preset["uses"], mixer["tie"], mixer["streak"], mixer["budget"], score)
    return algos.order_by(colors, [score(preset["algo"], colors, voats)])


class ShippedPresetTests(unittest.TestCase):
    def test_the_shipped_presets(self):
        self.assertEqual(factory.preset_names(factory.HERE), ["balanced", "discover", "mixer", "popular"])

    def test_every_generated_ranker_runs_on_its_own_and_matches_the_algos(self):
        folder = tempfile.mkdtemp()
        try:
            for name in factory.preset_names(factory.HERE):
                made = factory.generate(factory.HERE, name)
                self.assertTrue(made["ok"], made["error"])
                path = os.path.join(folder, "ranker_" + name + ".py")
                with open(path, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(made["value"])
                ranker = load_module(path, "ranker_" + name)
                preset = factory.read_preset(factory.HERE, name)["value"]
                for voats in LOGS:
                    board = ranker.rank(voats, COLORS)
                    self.assertEqual(sorted(board), sorted(COLORS), name)
                    self.assertEqual(board, reference_rank(preset, voats, COLORS), name)
        finally:
            shutil.rmtree(folder)

    def test_generating_is_repeatable(self):
        for name in factory.preset_names(factory.HERE):
            self.assertEqual(factory.generate(factory.HERE, name)["value"], factory.generate(factory.HERE, name)["value"])

    def test_the_committed_rankers_are_up_to_date(self):
        self.assertEqual(factory.check(factory.HERE, factory.preset_names(factory.HERE)), [])

    def test_a_ranker_holds_its_weights_and_only_the_code_it_needs(self):
        text = factory.generate(factory.HERE, "balanced")["value"]
        self.assertTrue(text.startswith("# Generated by factory.py - do not edit."))
        self.assertIn('MIX = {"similar": 0.6, "explore": 0.3, "net": 0.1}', text)
        self.assertIn("SIMILAR_REACH = 0.15", text)
        self.assertIn("def similar(", text)
        self.assertNotIn("def wilson(", text)
        self.assertNotIn("def mixer(", text)
        self.assertNotIn("import algos", text)


class FileTests(unittest.TestCase):
    """Each test works on a copy of weights/ and presets/ in a temporary folder."""

    def setUp(self):
        self.root = tempfile.mkdtemp()
        shutil.copytree(os.path.join(factory.HERE, "weights"), os.path.join(self.root, "weights"))
        shutil.copytree(os.path.join(factory.HERE, "presets"), os.path.join(self.root, "presets"))

    def tearDown(self):
        shutil.rmtree(self.root)

    def write(self, relative, text):
        with open(os.path.join(self.root, relative), "w", encoding="utf-8") as handle:
            handle.write(text)

    def remove(self, relative):
        os.remove(os.path.join(self.root, relative))

    def error(self, name):
        made = factory.generate(self.root, name)
        self.assertFalse(made["ok"])
        return made["error"]

    def test_json_weights_and_presets_load_like_toml(self):
        self.remove("weights/net.toml")
        self.write("weights/net.json", json.dumps({"up": 2.0, "down": 0.5}))
        made = factory.generate(self.root, "balanced")
        self.assertTrue(made["ok"], made["error"])
        self.assertIn("NET_UP = 2.0", made["value"])
        self.assertIn("# Weights: weights/similar.toml, weights/explore.toml, weights/net.json", made["value"])
        self.write("presets/plain.json", json.dumps({"algo": "net"}))
        self.assertTrue(factory.generate(self.root, "plain")["ok"])

    def test_both_files_or_neither_is_an_error(self):
        self.write("weights/net.json", "{}")
        self.assertIn("both weights/net.toml and weights/net.json", self.error("balanced"))
        self.remove("weights/net.json")
        self.remove("weights/net.toml")
        self.assertIn("missing weights/net.toml", self.error("balanced"))
        self.assertIn("missing presets/nothing.toml", self.error("nothing"))

    def test_an_unknown_algo_names_the_file(self):
        self.write("presets/odd.toml", 'algo = "magic"\n')
        error = self.error("odd")
        self.assertIn("presets/odd.toml", error)
        self.assertIn("magic", error)
        self.write("presets/odd.toml", 'algo = "mixer"\nuses = ["net", "magic"]\n')
        self.assertIn("magic", self.error("odd"))

    def test_a_missing_or_bad_weight_names_the_file_and_the_weight(self):
        cases = (("reach = 0.15\nup = 1.0\n", "missing weight 'down'"),
                 ('reach = 0.15\nup = 1.0\ndown = "hard"\n', "'down' must be a number"),
                 ("reach = 0\nup = 1.0\ndown = 1.0\n", "'reach' must be above 0"),
                 ("reach = nan\nup = 1.0\ndown = 1.0\n", "'reach' must be a number"),
                 ("reech = 0.15\nreach = 0.15\nup = 1.0\ndown = 1.0\n", "unknown weight 'reech'"),
                 ("reach = = 0.15\n", "weights/similar.toml: "))
        for text, words in cases:
            self.write("weights/similar.toml", text)
            error = self.error("balanced")
            self.assertIn("weights/similar.toml", error)
            self.assertIn(words, error)

    def test_preset_shapes_are_checked(self):
        cases = (('algo = "blend"\nuses = ["net"]\n', "blend needs a table"),
                 ('algo = "blend"\nuses = {net = "a lot"}\n', "must be a number"),
                 ('algo = "mixer"\nuses = {net = 1.0}\n', "the mixer needs a list"),
                 ('algo = "mixer"\nuses = ["net", "net"]\n', "listed twice"),
                 ('algo = "net"\nuses = ["net"]\n', "only blend and mixer take uses"),
                 ('algo = "net"\nextra = 1\n', "unknown key 'extra'"))
        for text, words in cases:
            self.write("presets/shape.toml", text)
            self.assertIn(words, self.error("shape"), text)

    def test_bad_preset_names_are_refused(self):
        self.assertIn("preset names", self.error("../weights/net"))
        self.assertIn("preset names", self.error("Mixer"))

    def test_a_single_scorer_preset_ranks_by_that_scorer(self):
        self.write("presets/plain.toml", 'algo = "wilson"\n')
        made = factory.ensure(self.root, "plain")
        self.assertTrue(made["ok"], made["error"])
        ranker = load_module(made["value"]["path"], "ranker_plain")
        voats = LOGS[2]
        self.assertEqual(ranker.rank(voats, COLORS), algos.order_by(COLORS, [algos.wilson(COLORS, voats, 1.96)]))

    def test_ensure_writes_only_when_the_ranker_is_missing_or_stale(self):
        self.assertTrue(factory.ensure(self.root, "mixer")["value"]["written"])
        self.assertFalse(factory.ensure(self.root, "mixer")["value"]["written"])
        self.write("weights/mixer.toml", "tie = 0.01\nstreak = 2\nbudget = 1000\n")
        self.assertEqual(len(factory.check(self.root, ["mixer"])), 1)
        self.assertTrue(factory.ensure(self.root, "mixer")["value"]["written"])
        self.assertEqual(factory.check(self.root, ["mixer"]), [])
        path = factory.ranker_path(self.root, "mixer")
        with open(path, "r", encoding="utf-8") as handle:
            text = handle.read()
        with open(path, "w", encoding="utf-8", newline="\r\n") as handle:
            handle.write(text)
        self.assertEqual(factory.check(self.root, ["mixer"]), [])


if __name__ == "__main__":
    unittest.main()

